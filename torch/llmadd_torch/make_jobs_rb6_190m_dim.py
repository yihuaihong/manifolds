import ast
import hashlib
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()[:12]
FROZEN = {"make_jobs_rb6scale.py": "19bc055c2d09", "rb6scale_refs.json": "b65472eb3d29",
          "make_jobs_rb6_190m_ext.py": "ba2eb39015af"}
for f_, v_ in FROZEN.items():
    assert sha(HERE / f_) == v_, (f_, sha(HERE / f_), v_, "a frozen generator / reference file changed")
for f_ in ("make_jobs_rb6scale.py", "make_jobs_rb6_190m_ext.py"):   # importing them must not run their main()
    _tree = ast.parse((HERE / f_).read_text())
    _calls = [n for n in _tree.body if isinstance(n, ast.Expr) and isinstance(n.value, ast.Call)]
    _guard = [n for n in _tree.body if isinstance(n, ast.If) and ast.unparse(n.test) == "__name__ == '__main__'"]
    assert not _calls and len(_guard) == 1 and ast.unparse(_guard[0].body[0]) == "main()", f"{f_} runs code on import"
sys.path.insert(0, str(HERE))
import make_jobs_rb6scale as M          # noqa: E402  render() (read-only file)
import make_jobs_rb6_190m_ext as X      # noqa: E402  snapshot() only (frozen file)

BATCH, SIZE = "rb6_190m_dim", "190m"
R = M.B / "runs" / BATCH
SNAP_COMMIT = "c6dcb6e"                       # = runs/rb6_190m/code/COMMIT (X.SNAP_COMMIT, asserted)
NICE_OLD, NICE_NEW = "#SBATCH --nice=20\n", "#SBATCH --nice=5000\n"
NONE_GRID = ("6e-4", "4.8e-3", "9.6e-3", "1.92e-2", "3.84e-2")   # = rb6scale_dim_summary.NONE_GRID
D1 = [("none", "3.84e-2")]
D1_SEEDS, D2_SEEDS = (0, 1, 2, 3), (4, 5, 6, 7)
ALL6 = ("all6-lam1", "6e-4")
REUSE_FROM = ("rb6_190m", "rb6_190m_ext")    # the batches with the same code snapshot (c6dcb6e)
REFS = M.B / "scale_work" / "rb190dim_refs.json"
BURST_DRY_NEW = {4: "470-rb6pb-53m-2pct-k2-none-s4", 5: "472-rb6pb-53m-2pct-k2-none-s5",
                 6: "474-rb6pb-53m-2pct-k2-none-s6", 7: "476-rb6pb-53m-2pct-k2-none-s7"}
# the read-out tool the select job runs: tools/ of this commit on scale-ladder, frozen in runs/rb6_190m_dim/select_code
READOUT_COMMIT = "8251667"
SELECT_FILES = ("rb6scale_dim_summary.py", "rb6scale_summary.py", "rainbow6_summary.py", "rb6scale_select.py",
                "readout_rules.py", "make_rb6m_tasks.py", "make_rb6_tasks.py")
