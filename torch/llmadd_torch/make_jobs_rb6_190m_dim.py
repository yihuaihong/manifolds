def opt(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


def load_refs():
    """the batch's CPU references -> add seeds 4-7 to M.LM0 / M.DRY / M.BURST_DRY in memory (asserted absent before; the
    seeds 0-3 values asserted unchanged and = the references'). -> the refs dict"""
    X_ = json.loads(REFS.read_text())
    assert X_.get("all_hold") is True, f"{REFS}: not every identity held"
    for s in D1_SEEDS:
        assert tuple(X_["dry_seed"][str(s)]) == tuple(M.DRY[SIZE][s]) and s not in BURST_DRY_NEW, s
    for s in D2_SEEDS:
        if M.LM0[SIZE].get(s) == X_["lm0"][str(s)] and M.DRY[SIZE].get(s) == tuple(X_["dry_seed"][str(s)]):
            continue   # already added (a second call in one process)
        assert s not in M.LM0[SIZE] and s not in M.DRY[SIZE] and s not in M.BURST_DRY, (s, "a seed-4-7 value exists")
        M.LM0[SIZE][s] = X_["lm0"][str(s)]
        M.DRY[SIZE][s] = tuple(X_["dry_seed"][str(s)])
        M.BURST_DRY[s] = BURST_DRY_NEW[s]
    return X_


def cells_of(stage, picks):
    """-> [(arm, lr, seed)] seed-major, and the pick (D2)"""
    if stage == "D1":
        return [(a, lr, s) for s in D1_SEEDS for a, lr in D1], None
    assert stage == "D2", stage
    assert picks is not None, "--stage D2 needs --picks <picks.json>"
    pk = json.loads(Path(picks).read_text())
    assert pk.get("batch") == BATCH and pk.get("status") == "picked" and pk.get("grid") == list(NONE_GRID), \
        ("picks.json: not a 'picked' selection of this batch", pk.get("batch"), pk.get("status"), pk.get("grid"))
    best = pk["pick"]["none_dim"]
    assert best in NONE_GRID, best
    cm = (R / "select_code" / "COMMIT").read_text()
    assert f"rb6scale_dim_summary.py {pk.get('tool_sha')}" in cm, ("picks.json not written by the frozen select tool",
                                                                   pk.get("tool_sha"))
    return [(a, lr, s) for s in D2_SEEDS for a, lr in (("none", best), ALL6)], best


def reused(name):
    """a run of this name in another batch: REUSED if that batch has this batch's code (REUSE_FROM) and the run finished
    with check.json PASS; any other batch: refused (never another batch's out dir)."""
    hits = [p for p in M.B.glob(f"runs/*/out/{name}") if p.parent.parent.name != BATCH]
    if not hits:
        return None
    assert len(hits) == 1 and hits[0].parent.parent.name in REUSE_FROM, (name, hits)
    cj = json.loads((hits[0] / "check.json").read_text())
    assert cj.get("pass") is True, (name, "the existing run did not pass its checks: not reused, decide by hand")
    return hits[0]


def build(stage, picks=None, refs_gate=True):
    """render the stage's jobs in memory -> [(name, text, args, intent) | (name, None, reused path, None)]"""
    head = X.snapshot(R)
    assert head == SNAP_COMMIT == X.SNAP_COMMIT and X.SRC_BATCH == M.B / "runs" / "rb6_190m", head
    pin_sha = M.WANT_SHA["pretrain_range.py"]
    assert M.WANT_SHA == X.WANT_SHA and M.SIZES[SIZE] == X.SIZES[SIZE] and (M.ACCOUNT, M.PARTITION, M.QOS, M.NICE) == \
        ("torch_pr_520_tandon_priority", "a100_tandon", "gpu48", 20)
    sys.path.insert(0, str(R / "code" / "tools"))
    import make_rb6m_tasks as G   # the snapshot's generator modules (as make_jobs_rb6scale.main)
    import make_rb6_tasks as P
    for mod in (G, P):
        assert Path(mod.__file__).resolve().parent == (R / "code" / "tools").resolve(), mod.__file__
    refs = load_refs() if refs_gate else None
    cells, best = cells_of(stage, picks)
    out = []
    for arm, lr, s in cells:
        tag = M.tag_of(SIZE, arm, lr)
        name = f"{tag}-s{s}"
        prev = reused(name)
        if prev is not None:
            out.append((name, None, prev, None))
            continue
        if refs_gate:   # the CPU --dry_inputs of exactly this (arm, lr, seed): rc 0, rows = the seed's DRY, priors = intent
            d = refs["dry"].get(f"{arm}@{lr}@s{s}")
            assert d and d["good"] and (d["sha"], d["n"]) == tuple(M.DRY[SIZE][s]), (name, "no / failed CPU dry reference", d)
        name_, tag_, text, args, I = M.render(G, P, R, SIZE, arm, lr, s, pin_sha)
        assert (name_, tag_) == (name, tag)
        assert text.count(NICE_OLD) == 1 and text.count("--nice") == 1, name
        text = text.replace(NICE_OLD, NICE_NEW)
        assert I["args"]["seed"] == s and I["args"]["lr"] == float(lr) and I["lm0_ref"] == M.LM0[SIZE][s] and \
            I["data_sha0"] == G.DSHA0[s] and I["dom"] == G.DOMS[s], name
        out.append((name, text, args, I))
    return out, head, pin_sha, best


def select_job_text(r=None, b=None, gen=None):
    """the selection job (rendered at D1 time; r / b / gen are overridable for the plumbing test only)."""
    r, b = r or R, b or M.B
    gen = gen or f'"$PY" {b}/make_jobs_rb6_190m_dim.py'
    cm = (R / "select_code" / "COMMIT").read_text()
    chk = "\n".join(f'grep -q "{f} $(sha256sum {f} | cut -c1-12)" "$R/select_code/COMMIT" || {{ echo "## {f} differs from '
                    f'select_code/COMMIT: exiting" | tee -a "$LOG"; exit 3; }}' for f in SELECT_FILES)
    assert all(f"{f} " in cm for f in SELECT_FILES)
    return f"""#!/bin/bash
#SBATCH --job-name=llmadd_{BATCH}-select
#SBATCH --account={M.ACCOUNT}
#SBATCH --partition=cpu_short
#SBATCH --cpus-per-task=2
#SBATCH --mem=24G
#SBATCH --time=02:00:00
#SBATCH --output={M.B}/logs/%x_%j.out
# {BATCH}: the pre-registered choice of none's dim lr on seeds 0-3 (runs/{BATCH}/AUDIT.md "Selection"), then Stage D2.
# Submitted by make_jobs_rb6_190m_dim.py --stage D1 --submit with --dependency=afterany:<the D1 job ids>. Runs the frozen
# read-out tool (select_code = git archive of tools/ at {READOUT_COMMIT}); only if its status is "picked": the generator
# (sha256[:12] {sha(__file__)}, checked) --stage D2 --picks picks.json --test-only, then --submit. Log: runs/{BATCH}/select.log.
set -u
R={r}; B={b}; PY={M.PY}
LOG=$R/select.log
if [ -e "$R/HOLD" ]; then echo "HOLD present: exiting" | tee -a "$LOG"; exit 0; fi
echo "== selection $(date -u +%FT%TZ) job ${{SLURM_JOB_ID:-}} on $(hostname)" | tee -a "$LOG"
cd "$R/select_code/tools" || exit 3
{chk}
[ "$(sha256sum $B/make_jobs_rb6_190m_dim.py | cut -c1-12)" = "{sha(__file__)}" ] || {{ echo "## the generator changed since D1: exiting" | tee -a "$LOG"; exit 3; }}
[ "$(sha256sum $B/scale_work/rb190dim_refs.json | cut -c1-12)" = "{sha(REFS)}" ] || {{ echo "## the CPU references changed since D1: exiting" | tee -a "$LOG"; exit 3; }}
[ ! -e "$R/picks.json" ] || {{ echo "## picks.json exists: the selection runs once; exiting" | tee -a "$LOG"; exit 3; }}
export HF_HOME=$B/hf_cache PYTHONPATH=$B/pylib
"$PY" rb6scale_dim_summary.py select "$B/runs/rb6_190m/out" "$B/runs/rb6_190m_ext/out" "$R/out" --json "$R/picks.json" 2>&1 | tee -a "$LOG"
status=$("$PY" -c 'import json, sys; print(json.load(open(sys.argv[1]))["status"])' "$R/picks.json" 2>/dev/null || echo none)
echo "selection status: $status" | tee -a "$LOG"
if [ "$status" != "picked" ]; then
  echo "NOT PICKED: Stage D2 is not submitted (the problems above go to the user)" | tee -a "$LOG"; exit 0
fi
# a clean environment for the child sbatch calls (no SLURM_* / SBATCH_* of this job)
for v in $(env | grep -oE '^(SLURM|SBATCH)_[A-Za-z0-9_]*'); do unset "$v"; done
cd "$B"
{gen} --stage D2 --picks "$R/picks.json" --test-only 2>&1 | tee -a "$LOG"
{gen} --stage D2 --picks "$R/picks.json" --submit 2>&1 | tee -a "$LOG"
echo "== done $(date -u +%FT%TZ)" | tee -a "$LOG"
"""


def freeze_select_code():
    """runs/rb6_190m_dim/select_code = git archive of tools/ at READOUT_COMMIT + COMMIT (once; then verified)."""
    assert READOUT_COMMIT != "PENDING", "commit the read-out tool on scale-ladder first and set READOUT_COMMIT"
    sc = R / "select_code"
    if not sc.exists():
        tmp = R / "select_code.tmp"
        subprocess.run(["rm", "-rf", str(tmp)], check=True)
        tmp.mkdir(parents=True)
        subprocess.run(["tar", "-x", "-C", str(tmp)], input=X.git("archive", READOUT_COMMIT, "tools"), check=True)
        (tmp / "COMMIT").write_text(f"{READOUT_COMMIT} ({X.BRANCH}, committed; git archive of tools/); sha256[:12]: "
                                    + ", ".join(f"{f} {sha(tmp / 'tools' / f)}" for f in SELECT_FILES) + "\n")
        tmp.rename(sc)
    cm = (sc / "COMMIT").read_text()
    assert cm.split()[0] == READOUT_COMMIT, cm[:40]
    for f in SELECT_FILES:
        s_ = sha(sc / "tools" / f)
        assert f"{f} {s_}" in cm, f
        assert hashlib.sha256(X.git("show", f"{READOUT_COMMIT}:tools/{f}")).hexdigest()[:12] == s_, (f, READOUT_COMMIT)
    return cm


def main():
    stage = opt("--stage")
    assert stage in ("snapshot", "D1", "D2"), "--stage snapshot | D1 | D2"
    if stage == "snapshot":
        print(f"{BATCH}: snapshot {X.snapshot(R)} at {R / 'code'} (= runs/rb6_190m/code, asserted)")
        return
    submit = "--submit" in sys.argv
    if submit:   # pre-registration first; the CPU references always
        assert AUDIT_MARK in (R / "AUDIT.md").read_text(), "write runs/rb6_190m_dim/AUDIT.md (pre-registration) first"
    jobs, head, pin_sha, best = build(stage, opt("--picks"))
    if stage == "D1":
        freeze_select_code()
        txt = select_job_text()
        if (R / "SUBMITTED_select").exists():
            assert SELECT_JOB.read_text() == txt, "the submitted select job differs from this rendering"
        else:
            SELECT_JOB.write_text(txt)
    rows = []
    for name, text, args, I in jobs:
        if text is None:
            print(f"{name}: REUSED {args} (same code snapshot, check PASS): not rendered, not submitted")
            continue
        job, flag = R / f"job_{name}.sbatch", R / f"SUBMITTED_{name}"
        if flag.exists():   # a submitted job file is never rewritten
            if job.read_text() != text:
                print(f"WARNING: {job.name} was submitted and differs from this rendering: kept, not rewritten")
        else:
            job.write_text(text)
        rows.append((name, job, flag, args))
    if "--print" in sys.argv:
        for name, job, flag, args in rows:
            print(f"{name}: {args}")
    for name, job, flag, args in rows:
        if "--test-only" in sys.argv:
            o = subprocess.run(["sbatch", "--test-only", str(job)], capture_output=True, text=True)
            print(name, (o.stdout + o.stderr).strip())
    ids, failed = [], []
    for name, job, flag, args in rows:
        if submit and not flag.exists():
            o = subprocess.run(["sbatch", str(job)], capture_output=True, text=True)
            print(name, (o.stdout + o.stderr).strip())
            if o.returncode == 0:
                flag.write_text(o.stdout)
            else:
                failed.append(name)
        if flag.exists():
            ids.append(flag.read_text().split()[-1])
    if stage == "D1" and "--test-only" in sys.argv:
        o = subprocess.run(["sbatch", "--test-only", str(SELECT_JOB)], capture_output=True, text=True)
        print("select", (o.stdout + o.stderr).strip())
    if stage == "D1" and submit:
        sf = R / "SUBMITTED_select"
        if sf.exists():
            print(f"select job already submitted: {sf.read_text().strip()}")
        elif failed or len(ids) != len(D1_SEEDS) * len(D1):
            print(f"## NOT submitting the select job: D1 jobs {failed} failed to submit ({len(ids)} ids)")
        else:
            o = subprocess.run(["sbatch", f"--dependency=afterany:{':'.join(ids)}", str(SELECT_JOB)], capture_output=True,
                               text=True)
            print("select", (o.stdout + o.stderr).strip())
            if o.returncode == 0:
                sf.write_text(o.stdout)
    print(f"{BATCH} {stage}: {len(rows)} jobs rendered in {R} (nice {NICE_NEW.split('=')[1].strip()})"
          + (f", none_dim {best}" if best else "") + f"; code {head}, trainer {pin_sha}; submitted: {'yes' if submit else 'no'}")


if __name__ == "__main__":
    main()
