#!/usr/bin/env python
"""pt6v2 Amendment V6 (exp-builder 2026-11-22): build the probe-only copy of the V5 trainer for probe_v6.

Reads   runs/pt6v2/out_v5/code/tools/pretrain_range.py   (the V5 trainer, sha 041b2f4241b9; never modified)
Writes  runs/pt6v2/probe_v6_lib/pretrain_range_probe6.py (generated; regenerate, do not hand-edit)

The same four counted edits as probe_v5_lib/make_probe_copy.py (V5 audit: the trainer's own main() builds the eval prompts,
item sites, answer spans, model and hooks up to the SAVE_AT print), each asserted to match exactly once:
  E1  sys.path: the V5 tools dir and this lib dir importable from the copy's location
  E2  argparse: --probe_wts (one weight file) and --probe6_out (output dir) [+ --probe6_cfg JSON string]
  E3  --probe6_out skips run_guard.claim (no .claim file)
  E4  after the SAVE_AT print: probe6_inner.run(locals of main) then return (no optimizer step, no training)
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

LIB = Path(__file__).resolve().parent
TOOLS = LIB.parent / "out_v5" / "code" / "tools"
SRC = TOOLS / "pretrain_range.py"
DST = LIB / "pretrain_range_probe6.py"
EXPECT_SHA = "041b2f4241b9"   # the V5 trainer (HANDOFF_V5.md)

EDITS = [
    ("E1", "import numlib as nl\n",
     f"import sys as _probe_sys   # probe_v6 E1\n_probe_sys.path[:0] = [{str(TOOLS)!r}, {str(LIB)!r}]   # probe_v6 E1\n"
     "import numlib as nl\n"),
    ("E2", '    ap.add_argument("--seed", type=int, default=0)\n',
     '    ap.add_argument("--probe_wts", default="", help="probe_v6 E2: one weight file (state_dict)")\n'
     '    ap.add_argument("--probe6_out", default="", help="probe_v6 E2: write the V6 read-out here, then exit")\n'
     '    ap.add_argument("--probe6_cfg", default="{}", help="probe_v6 E2: JSON config of the read-out")\n'
     '    ap.add_argument("--seed", type=int, default=0)\n'),
    ("E3", "    if not args.dry_inputs:   # the same run may be queued twice",
     "    if not args.dry_inputs and not args.probe6_out:   # probe_v6 E3 (no claim) | the same run may be queued twice"),
    ("E4", "        print(f\"save_model_at: steps {SAVE_AT} of {steps} (weights only, after the step's update = the weights its eval logs)\", flush=True)\n",
     "        print(f\"save_model_at: steps {SAVE_AT} of {steps} (weights only, after the step's update = the weights its eval logs)\", flush=True)\n"
     "    if args.probe6_out:   # probe_v6 E4: the V6 read-out of --probe_wts, no training\n"
     "        import probe6_inner\n"
     "        probe6_inner.run(dict(locals()), src_sha=" + repr("@SRC_SHA@") + ")\n"
     "        return\n"),
]


def build() -> str:
    raw = SRC.read_bytes()
    sha = hashlib.sha256(raw).hexdigest()[:12]
    txt = raw.decode()
    for name, old, new in EDITS:
        n = txt.count(old)
        assert n == 1, (name, "anchor count", n)
        txt = txt.replace(old, new.replace("@SRC_SHA@", sha))
    hdr = f"# GENERATED by runs/pt6v2/probe_v6_lib/make_probe_copy6.py from {SRC} (sha {sha}); edits E1-E4 marked 'probe_v6'\n"
    new = hdr + txt
    if not DST.exists() or DST.read_text() != new:   # array tasks build it concurrently: write only when it changes
        tmp = DST.with_suffix(f".tmp{__import__('os').getpid()}")
        tmp.write_text(new)
        tmp.replace(DST)
    return sha


if __name__ == "__main__":
    sha = build()
    print(f"probe copy: {DST} from {SRC.name} sha {sha} (expected {EXPECT_SHA}: {'OK' if sha == EXPECT_SHA else 'MISMATCH'})")
    if sha != EXPECT_SHA and "--allow_sha" not in sys.argv:
        sys.exit(f"source trainer sha {sha} != {EXPECT_SHA}")
