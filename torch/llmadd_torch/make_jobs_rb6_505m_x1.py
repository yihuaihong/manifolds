"""Torch jobs (2026-10-25): Amendment X1 of runs/rb6_505m (runs/rb6_505m/AUDIT.md "Amendment X1"): one more none lr below
the 505M sweep's grid, none@2.4e-3, seeds 0-1 (2 jobs; the selection picked none 4.8e-3 at the lower edge of its grid ->
bracket OPEN; one more step outward = the user's call, approved 2026-10-25 "你觉得有必要的实验我觉得就可以跑").
NOT a copy: imports make_jobs_rb6scale (READ-ONLY, sha256[:12] 19bc055c2d09, rb6scale_refs.json b65472eb3d29; both
asserted) and reuses its snapshot(R) (verify-only: runs/rb6_505m/code exists, commit 7f1d06b) and render(G, P, R, size,
arm, lr, seed, pin_sha) with every assert inside it (flags = intent, step-0 lm reference, DRY row hash vs the Burst 53M
rows, the job's sha checks), and main()'s SUBMITTED_<name> flag / never-rewrite / --print / --test-only / --submit logic.
make_jobs_rb6scale's main() runs only under __name__ == "__main__" (asserted below: importing it renders and submits
nothing). The job files therefore say "generated by llmadd_torch/make_jobs_rb6scale.py": render() is that file's,
unchanged; this file only drives it for the X1 cells. A job differs from the sweep's none@4.8e-3 job of the same seed only
in the lr, the tag, the out dir and the job name (scratchpad x1/jobcheck_x1.py).
    python make_jobs_rb6_505m_x1.py [--print] [--test-only] [--submit]"""
import ast
import hashlib
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()[:12]
FROZEN = {"make_jobs_rb6scale.py": "19bc055c2d09", "rb6scale_refs.json": "b65472eb3d29"}   # AUDIT.md Freeze note
for f_, v_ in FROZEN.items():
    assert sha(HERE / f_) == v_, (f_, sha(HERE / f_), v_, "the frozen 505M generator / references changed")
# importing make_jobs_rb6scale must not run its main(): its only top-level call of main() is under the __main__ guard
_tree = ast.parse((HERE / "make_jobs_rb6scale.py").read_text())
_calls = [n for n in _tree.body if isinstance(n, ast.Expr) and isinstance(n.value, ast.Call)]
_guard = [n for n in _tree.body if isinstance(n, ast.If) and ast.unparse(n.test) == "__name__ == '__main__'"]
assert not _calls and len(_guard) == 1 and ast.unparse(_guard[0].body[0]) == "main()", "make_jobs_rb6scale runs code on import"
sys.path.insert(0, str(HERE))
import make_jobs_rb6scale as M   # noqa: E402

BATCH = "rb6_505m"
CELLS = [("none", "2.4e-3")]   # X1: none@2.4e-3 = 4.8e-3 / 2 (the grid's factor-2 step), below the pre-registered grid
SEEDS = (0, 1)
SNAP_COMMIT = "7f1d06b"


def main():
    cfg = M.BATCHES[BATCH]
    size = cfg["size"]
    assert size == "505m" and Path(M.__file__).resolve() == (HERE / "make_jobs_rb6scale.py").resolve()
    for c in CELLS:   # outside the pre-registered sweep (X1 is an amendment, not a sweep cell)
        assert c not in cfg["stages"]["sweep"], c
    R = M.B / "runs" / BATCH
    assert (R / "code" / "COMMIT").exists(), "the batch snapshot must exist (snapshot() then only verifies it)"
    head = M.snapshot(R)
    assert head == SNAP_COMMIT, (head, SNAP_COMMIT)
    pin_sha = M.WANT_SHA["pretrain_range.py"]
    au = (R / "AUDIT.md").read_text()
    assert "## Amendment X1" in au, "Amendment X1 must be in runs/rb6_505m/AUDIT.md before any X1 job is rendered"
    sys.path.insert(0, str(R / "code" / "tools"))
    import make_rb6m_tasks as G   # the snapshot's generator modules (as make_jobs_rb6scale.main)
    import make_rb6_tasks as P
    for mod in (G, P):
        assert Path(mod.__file__).resolve().parent == (R / "code" / "tools").resolve(), mod.__file__
    existing = {p.name for p in M.B.glob("runs/*/out/*")}
    jobs = []
    for arm, lr in CELLS:
        for s in SEEDS:
            name, tag, text, args, I = M.render(G, P, R, size, arm, lr, s, pin_sha)
            assert name not in existing or (R / "out" / name).exists(), name   # never another batch's out dir
            job = R / f"job_{name}.sbatch"
            flag = R / f"SUBMITTED_{name}"
            if flag.exists():   # a submitted job file is never rewritten
                if job.read_text() != text:
                    print(f"WARNING: {job.name} was submitted and differs from this rendering: kept, not rewritten")
            else:
                job.write_text(text)
            jobs.append((name, job, flag, args))
    if "--print" in sys.argv:
        for name, job, flag, args in jobs:
            print(f"{name}: {args}")
    for name, job, flag, args in jobs:
        if "--test-only" in sys.argv:
            o = subprocess.run(["sbatch", "--test-only", str(job)], capture_output=True, text=True)
            print(name, (o.stdout + o.stderr).strip())
        if "--submit" in sys.argv and not flag.exists():
            o = subprocess.run(["sbatch", str(job)], capture_output=True, text=True)
            print(name, (o.stdout + o.stderr).strip())
            if o.returncode == 0:
                flag.write_text(o.stdout)
    print(f"{BATCH} X1: {len(jobs)} jobs rendered in {R}; code {head}, trainer {pin_sha}; "
          f"submitted: {'yes' if '--submit' in sys.argv else 'no'}")


if __name__ == "__main__":
    main()
